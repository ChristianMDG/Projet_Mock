BEGIN;

ALTER TABLE shop_order DROP CONSTRAINT IF EXISTS shop_order_status_check;

ALTER TABLE shop_order ADD CONSTRAINT shop_order_status_check
  CHECK (status::text = ANY (ARRAY[
    'PENDING','CONFIRMED','PAYMENT_FAILED','PROCESSING','SHIPPED',
    'READY_IN_STORE','DELIVERY_TO_STATION','DELIVERY_IN_PROGRESS',
    'AVAILABLE_AT_COUNTER','DELIVERED','CANCELLED'
  ]));

ALTER TABLE shop_order DROP CONSTRAINT IF EXISTS shop_order_previous_status_check;

ALTER TABLE shop_order ADD CONSTRAINT shop_order_previous_status_check
  CHECK (
    previous_status IS NULL
    OR previous_status::text = ANY (ARRAY[
      'PENDING','CONFIRMED','PAYMENT_FAILED','PROCESSING','SHIPPED',
      'READY_IN_STORE','DELIVERY_TO_STATION','DELIVERY_IN_PROGRESS',
      'AVAILABLE_AT_COUNTER','DELIVERED','CANCELLED'
    ])
  );

COMMIT;